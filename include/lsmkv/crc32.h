// ══════════════════════════════════════════════════════════════
//  CRC32 —— 2026-10-26
//
//  ★ 先回答一个问题：现在的 Load 已经能认错了，为什么还要 CRC？
//
//    你现在的 Decode 靠什么判断"这条记录是坏的"？靠**长度检查**：
//        if (p + klen > limit) return false;
//    这个检查能抓住一种错 —— 长度明显越界。但它抓不住下面这些：
//
//      · 磁盘老化，中间某个字节从 'a' 变成了 'q'
//        → 长度还是对的，Decode 照样成功，你读出一个**错的 value**，
//          而且全程没有任何报错。这叫**静默错误**，是存储里最坏的一种。
//
//      · 崩溃时写了半条，但半条的长度字段恰好落在合理范围内
//        → 同样"成功"解析，后面全错位。
//
//    也就是说：**长度检查保证"结构没崩"，不保证"内容没变"。**
//    CRC 补的就是这一块 —— 它是这段字节的**指纹**：
//
//        同样的字节 → 同样的 CRC
//        改了一个 bit → CRC 几乎一定不同（32 位空间里撞车概率 1/2^32）
//
//    所以 Load 的流程会变成：
//        读出 crc 字段 → 对记录体重算一遍 → 两个数不相等 → 这条坏了
//    注意：**CRC 只能检测，不能修复。** 检测到就丢弃（并记日志），修不了。
//
//  ★ CRC32 到底在算什么？
//
//    把整串字节看成一个巨大的二进制数（多项式），
//    去除一个固定的"生成多项式"，**余数**就是 CRC。
//
//    "模 2 除法"里没有进位，减法等于加法等于异或（XOR）——
//    所以整个算法只有两种运算：**移位** 和 **异或**。
//    这就是它快的原因：没有任何乘除，全是位运算。你的主场。
//
//  ★ 为什么要查表？（今天真正要理解的东西）
//
//    朴素做法：对每个字节做 8 轮移位异或。1 MB 数据 = 800 万轮。
//    查表法：一个字节可能的取值只有 256 种，"这个字节经过 8 轮会得到
//            什么"是可以**预先算好**的 —— 存成 256 项的数组。
//            之后每个字节只需要：查一次表 + 两次异或。
//
//    代价：1 KB 内存。收益：快约 8 倍。
//
//    **这是"空间换时间"最经典的案例，也是你以后会反复遇到的原型**：
//    AES 的 S-box、Base64 的编码表、大小写转换表、UTF-8 解码表 ——
//    全是同一个套路：把"按规则算"换成"查预先算好的结果"。
//
//  ★ 表长什么样
//
//    table[i] = 让字节 i 单独走完 8 轮之后的结果。i 从 0 到 255。
//    多项式用 **0xEDB88320**（这是标准 CRC-32 用的那个，叫反射形式，
//    别问为什么是反的，标准就这么定的，各家实现都用它，你照用即可）。
//
// ══════════════════════════════════════════════════════════════

// ─────────────────────────────────────────────────────────────
//  任务 1：算表
//
//  规格：对每个 i ∈ [0, 255]，做 8 轮下面这件事：
//
//      看 i 的最低位
//        最低位是 1  →  i 右移一位，然后异或 0xEDB88320
//        最低位是 0  →  只右移一位
//
//  8 轮走完，得到的结果就是 table[i]。
//
//  提示：
//    · "看最低位" = `c & 1`
//    · 这个过程不能改 i 本身（i 还要当索引用），所以先 `uint32_t c = i;`
//    · 8 轮 → 循环 8 次
//    · **关于 `uint32_t` 的右移**：无符号右移是逻辑右移，高位补 0。
//      这里必须用无符号，用 int 会在高位补符号位，结果全错。
//
//  为什么这个"8 轮"是正确的，等跑通了再回来看这一段：
//    一个字节有 8 个 bit，每一位都要参与一次模 2 除法，
//    一次"移位 + 条件异或"正好处理一位。
// ─────────────────────────────────────────────────────────────
inline const uint32_t* Crc32Table() {
  static uint32_t table[256];
  static bool ready = false;

  if (!ready) {
    for(uint32_t i = 0;i < 256;++i){
      uint32_t c = i;
      for(int j = 0;j < 8;++j){
        if(c & 1) c >>= 1,c ^= 0xEDB88320;
        else c >>= 1;
      }
      table[i] = c;
    }
    ready = true;
  }
  return table;
}

// ─────────────────────────────────────────────────────────────
//  任务 2：算整串字节的 CRC
//
//  三步，顺序不能换：
//
//    ① 初值 crc = 0xFFFFFFFF      （不是 0 —— 标准规定的，防前导零被忽略）
//    ② 对每个字节 b：
//         a. crc 的低 8 位 和 b 异或 → 得到一个 0..255 的数 → 拿它查表
//         b. crc 右移 8 位
//         c. crc 异或上刚才查到的表项
//    ③ 最后 crc = crc ^ 0xFFFFFFFF  （取反，也是标准规定的）
//
//  ②里那三步合成一行就是全部核心。想清楚"为什么先异或再移再查表"：
//    因为一次要吃掉 8 个 bit，所以 crc 整体往右腾出 8 位，
//    而"这 8 个 bit 该怎么影响余数"的结果，正好就是表里那 256 项之一。
//
//  提示：
//    · 取低 8 位：`crc & 0xFF`
//    · 字符是无符号还是要转？`char` 在 x86 上**有符号**，b 可能被当成负数。
//      所以读字节时转成 `uint8_t` 再参与运算，否则高位会污染结果。
//    · 循环里 `data[i]` 是 char，注意上面那条。
// ─────────────────────────────────────────────────────────────
inline uint32_t Crc32(const char* data, size_t n) {
  const uint32_t* table = Crc32Table();
  uint32_t crc = 0xFFFFFFFFu;
  for (size_t i = 0; i < n; ++i) {
    uint8_t byte = static_cast<uint8_t>(data[i]);
    uint32_t index = (crc ^ byte) & 0xFFu;
    crc = (crc >> 8) ^ table[index];
  }
  return crc ^ 0xFFFFFFFFu;
}

inline uint32_t Crc32(const std::string& s) {
  return Crc32(s.data(), s.size());
}

